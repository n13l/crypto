static inline void
aria_xor(u8 r[16], const u8 a[16], const u8 b[16])
{
	unsigned int i;

	for (i = 0; i < 16; i++)
		r[i] = a[i] ^ b[i];
}

static void
aria_sl1(u8 x[16])
{
	unsigned int i;

	for (i = 0; i < 16; i += 4) {
		x[i]     = aria_sb1[x[i]];
		x[i + 1] = aria_sb2[x[i + 1]];
		x[i + 2] = aria_sb3[x[i + 2]];
		x[i + 3] = aria_sb4[x[i + 3]];
	}
}

static void
aria_sl2(u8 x[16])
{
	unsigned int i;

	for (i = 0; i < 16; i += 4) {
		x[i]     = aria_sb3[x[i]];
		x[i + 1] = aria_sb4[x[i + 1]];
		x[i + 2] = aria_sb1[x[i + 2]];
		x[i + 3] = aria_sb2[x[i + 3]];
	}
}

static void
aria_a(u8 y[16], const u8 x[16])
{
	y[0]  = x[3]  ^ x[4]  ^ x[6]  ^ x[8]  ^ x[9]  ^ x[13] ^ x[14];
	y[1]  = x[2]  ^ x[5]  ^ x[7]  ^ x[8]  ^ x[9]  ^ x[12] ^ x[15];
	y[2]  = x[1]  ^ x[4]  ^ x[6]  ^ x[10] ^ x[11] ^ x[12] ^ x[15];
	y[3]  = x[0]  ^ x[5]  ^ x[7]  ^ x[10] ^ x[11] ^ x[13] ^ x[14];
	y[4]  = x[0]  ^ x[2]  ^ x[5]  ^ x[8]  ^ x[11] ^ x[14] ^ x[15];
	y[5]  = x[1]  ^ x[3]  ^ x[4]  ^ x[9]  ^ x[10] ^ x[14] ^ x[15];
	y[6]  = x[0]  ^ x[2]  ^ x[7]  ^ x[9]  ^ x[10] ^ x[12] ^ x[13];
	y[7]  = x[1]  ^ x[3]  ^ x[6]  ^ x[8]  ^ x[11] ^ x[12] ^ x[13];
	y[8]  = x[0]  ^ x[1]  ^ x[4]  ^ x[7]  ^ x[10] ^ x[13] ^ x[15];
	y[9]  = x[0]  ^ x[1]  ^ x[5]  ^ x[6]  ^ x[11] ^ x[12] ^ x[14];
	y[10] = x[2]  ^ x[3]  ^ x[5]  ^ x[6]  ^ x[8]  ^ x[13] ^ x[15];
	y[11] = x[2]  ^ x[3]  ^ x[4]  ^ x[7]  ^ x[9]  ^ x[12] ^ x[14];
	y[12] = x[1]  ^ x[2]  ^ x[6]  ^ x[7]  ^ x[9]  ^ x[11] ^ x[12];
	y[13] = x[0]  ^ x[3]  ^ x[6]  ^ x[7]  ^ x[8]  ^ x[10] ^ x[13];
	y[14] = x[0]  ^ x[3]  ^ x[4]  ^ x[5]  ^ x[9]  ^ x[11] ^ x[14];
	y[15] = x[1]  ^ x[2]  ^ x[4]  ^ x[5]  ^ x[8]  ^ x[10] ^ x[15];
}

static void
aria_fo(u8 out[16], const u8 in[16], const u8 rk[16])
{
	u8 t[16];

	aria_xor(t, in, rk);
	aria_sl1(t);
	aria_a(out, t);
}

static void
aria_fe(u8 out[16], const u8 in[16], const u8 rk[16])
{
	u8 t[16];

	aria_xor(t, in, rk);
	aria_sl2(t);
	aria_a(out, t);
}

static void
aria_rotr(u8 out[16], const u8 in[16], unsigned int n)
{
	u64 hi = get_u64_be(in), lo = get_u64_be(in + 8);
	u64 rhi, rlo;

	if (n >= 64) {
		u64 t = hi; hi = lo; lo = t;
		n -= 64;
	}
	if (n) {
		rhi = (hi >> n) | (lo << (64 - n));
		rlo = (lo >> n) | (hi << (64 - n));
	} else {
		rhi = hi;
		rlo = lo;
	}
	put_u64_be(out, rhi);
	put_u64_be(out + 8, rlo);
}

static void
aria_rotl(u8 out[16], const u8 in[16], unsigned int n)
{
	aria_rotr(out, in, 128 - n);
}

int
aria_setkey(struct aria_ctx *ctx, const u8 *key, size_t key_len)
{
	u8 kl[16], kr[16], w[4][16], t[16];
	const u8 *ck1, *ck2, *ck3;
	unsigned int i, n;

	switch (key_len) {
	case 16: n = 12; ck1 = aria_c1; ck2 = aria_c2; ck3 = aria_c3; break;
	case 24: n = 14; ck1 = aria_c2; ck2 = aria_c3; ck3 = aria_c1; break;
	case 32: n = 16; ck1 = aria_c3; ck2 = aria_c1; ck3 = aria_c2; break;
	default: return -1;
	}
	ctx->rounds = n;

	memcpy(kl, key, 16);
	memset(kr, 0, 16);
	memcpy(kr, key + 16, key_len - 16);

	memcpy(w[0], kl, 16);
	aria_fo(t, w[0], ck1); aria_xor(w[1], t, kr);
	aria_fe(t, w[1], ck2); aria_xor(w[2], t, w[0]);
	aria_fo(t, w[2], ck3); aria_xor(w[3], t, w[1]);

#define EK(_i, _a, _b, _rot, _n) do { \
	aria_##_rot(t, w[_b], _n); \
	aria_xor(ctx->ek[(_i) - 1], w[_a], t); \
} while (0)
	EK(1,  0, 1, rotr, 19); EK(2,  1, 2, rotr, 19);
	EK(3,  2, 3, rotr, 19); EK(4,  3, 0, rotr, 19);
	EK(5,  0, 1, rotr, 31); EK(6,  1, 2, rotr, 31);
	EK(7,  2, 3, rotr, 31); EK(8,  3, 0, rotr, 31);
	EK(9,  0, 1, rotl, 61); EK(10, 1, 2, rotl, 61);
	EK(11, 2, 3, rotl, 61); EK(12, 3, 0, rotl, 61);
	EK(13, 0, 1, rotl, 31); EK(14, 1, 2, rotl, 31);
	EK(15, 2, 3, rotl, 31); EK(16, 3, 0, rotl, 31);
	EK(17, 0, 1, rotl, 19);
#undef EK

	memcpy(ctx->dk[0], ctx->ek[n], 16);
	for (i = 1; i < n; i++)
		aria_a(ctx->dk[i], ctx->ek[n - i]);
	memcpy(ctx->dk[n], ctx->ek[0], 16);
	return 0;
}

static void
aria_crypt_block(const u8 (*rk)[16], unsigned int n, const u8 *in, u8 *out)
{
	u8 a[16], b[16];
	unsigned int i;

	memcpy(a, in, 16);
	for (i = 0; i + 2 < n; i += 2) {
		aria_fo(b, a, rk[i]);
		aria_fe(a, b, rk[i + 1]);
	}
	aria_fo(b, a, rk[n - 2]);
	aria_xor(a, b, rk[n - 1]);
	aria_sl2(a);
	aria_xor(out, a, rk[n]);
}

void
aria_encrypt_block(const struct aria_ctx *ctx, const u8 *in, u8 *out)
{
	aria_crypt_block(ctx->ek, ctx->rounds, in, out);
}

void
aria_decrypt_block(const struct aria_ctx *ctx, const u8 *in, u8 *out)
{
	aria_crypt_block(ctx->dk, ctx->rounds, in, out);
}

int
aria_cbc_init_ctx_iv(struct aria_ctx *ctx, const u8 *key, size_t key_len,
                     const u8 *iv)
{
	if (aria_setkey(ctx, key, key_len))
		return -1;
	if (iv)
		memcpy(ctx->Iv, iv, ARIA_BLOCKLEN);
	else
		memset(ctx->Iv, 0, ARIA_BLOCKLEN);
	return 0;
}

void
aria_cbc_encrypt(struct aria_ctx *ctx, u8 *buf, u32 length)
{
	unsigned int i;

	for (; length >= ARIA_BLOCKLEN; length -= ARIA_BLOCKLEN, buf += ARIA_BLOCKLEN) {
		for (i = 0; i < ARIA_BLOCKLEN; i++)
			buf[i] ^= ctx->Iv[i];
		aria_encrypt_block(ctx, buf, buf);
		memcpy(ctx->Iv, buf, ARIA_BLOCKLEN);
	}
}

void
aria_cbc_decrypt(struct aria_ctx *ctx, u8 *buf, u32 length)
{
	u8 next[ARIA_BLOCKLEN];
	unsigned int i;

	for (; length >= ARIA_BLOCKLEN; length -= ARIA_BLOCKLEN, buf += ARIA_BLOCKLEN) {
		memcpy(next, buf, ARIA_BLOCKLEN);
		aria_decrypt_block(ctx, buf, buf);
		for (i = 0; i < ARIA_BLOCKLEN; i++)
			buf[i] ^= ctx->Iv[i];
		memcpy(ctx->Iv, next, ARIA_BLOCKLEN);
	}
}
