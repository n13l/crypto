/* ARIA: RFC 5794 Appendix A's 128-bit known answer, and ARIA-128-GCM against
 * OpenSSL over the RFC 8998 A.1 inputs (the same key, nonce, AAD and
 * plaintext, which is what makes the two AEAD tables comparable). */
static int test_aria(void)
{
	static const u8 key[32] = {
		0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
		0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f };
	static const u8 pt[16] = {
		0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff };
	static const u8 ct128[16] = {
		0xd7,0x18,0xfb,0xd6,0xab,0x64,0x4c,0x73,0x9d,0xa9,0x5f,0x3b,0xe6,0x45,0x17,0x78 };
	static const u8 ct256[16] = {
		0xf9,0x2b,0xd7,0xc7,0x9f,0xb7,0x2e,0x2f,0x2b,0x8f,0x80,0xc1,0x97,0x2d,0x24,0xfc };
	static const u8 gcm_tag[16] = {
		0x55,0xc8,0xa8,0x8f,0x40,0xa5,0xd9,0xa8,0x87,0x2b,0xc3,0xed,0x0a,0x52,0xce,0x22 };
	struct aria_ctx ctx;
	u8 out[80], dec[64];

	if (aria_setkey(&ctx, key, 16))
		return 0;
	aria_encrypt_block(&ctx, pt, out);
	if (!eq(out, ct128, 16))
		return 0;
	if (aria_setkey(&ctx, key, 32))
		return 0;
	aria_encrypt_block(&ctx, pt, out);
	if (!eq(out, ct256, 16))
		return 0;
	if (aria_gcm_encrypt_aad(out, sm_pt, 64, sm_aad, 20, key, 16, sm_iv, 12))
		return 0;
	if (!eq(out + 64, gcm_tag, 16))
		return 0;
	if (aria_gcm_decrypt_aad(dec, out, 80, sm_aad, 20, key, 16, sm_iv, 12) != 0 ||
	    !eq(dec, sm_pt, 64))
		return 0;
	return 1;
}
